"""Generate Python messages from descriptors, compatible with protobuf 3.20+."""

import subprocess
from pathlib import Path
from tempfile import TemporaryDirectory

from google.protobuf.descriptor_pb2 import FileDescriptorSet

ROOT = Path(__file__).resolve().parents[1]
with TemporaryDirectory() as temporary:
    descriptor = Path(temporary) / "schema.pb"
    subprocess.run(
        [
            "protoc",
            f"-I{ROOT / 'proto'}",
            f"--descriptor_set_out={descriptor}",
            f"--pyi_out={ROOT / 'src/koris_api/schema'}",
            "koris/v1/game.proto",
        ],
        check=True,
    )
    files = FileDescriptorSet.FromString(descriptor.read_bytes())
    for file in files.file:
        target = ROOT / "src/koris_api/schema" / file.name.replace(".proto", "_pb2.py")
        target.parent.mkdir(parents=True, exist_ok=True)
        module = "koris_api.schema." + file.name.replace("/", ".").replace(
            ".proto", "_pb2"
        )
        target.write_text(
            "# Generated by scripts/generate_proto.py. DO NOT EDIT.\n"
            "from google.protobuf import descriptor_pool\n"
            "from google.protobuf.internal import builder\n\n"
            f"DESCRIPTOR = descriptor_pool.Default().AddSerializedFile({file.SerializeToString()!r})\n"
            "builder.BuildMessageAndEnumDescriptors(DESCRIPTOR, globals())\n"
            f"builder.BuildTopDescriptorsAndMessages(DESCRIPTOR, {module!r}, globals())\n"
        )
